/**
 * CWE-035 shared constants and task identity helpers (Sections 19, 20).
 *
 * The council source-session tag is the recursion guard: every board task
 * this layer creates carries `source = 'council'` (the creation-only
 * provenance column createTaskCore stamps) AND the machine-readable tag
 * `[council-source-session:<session-id>]` as the first description line.
 * A council session convened over council output can therefore always be
 * detected, and council-generated work can never silently loop.
 */

/** tasks.source value for every task created by the council kanban layer. */
export const COUNCIL_TASK_SOURCE = 'council';

/**
 * The plan-assembly routing hold (Section 19.5). Passed to createTaskCore
 * as routing_hold_reason, it lands in tasks.dispatch_hold = 1 with
 * routing_wait_owner = 'SYSTEM': the creation-time router skips the task,
 * the dispatch-intent sweep requires an assigned agent (a held council
 * task never has one), the intake-advance sweep excludes held tasks from
 * assignment, and execution attempts refuse held tasks. CWE-036 adds the
 * dispatcher-sweep race tests (T159) on top of this mechanism.
 */
export const COUNCIL_PLAN_ASSEMBLING_HOLD = 'council_plan_assembling';

/** Typed handler identity for the parent session card (Section 19.3). */
export const COUNCIL_SESSION_HANDLER = 'council_session';

const TAG_PATTERN = /\[council-source-session:([^\]]+)\]/;

/** The source-session tag line stamped as the first description line. */
export function councilSourceSessionTag(sessionId: string): string {
  return `[council-source-session:${sessionId}]`;
}

/** True when a board task was generated by a council session. */
export function isCouncilGeneratedTask(task: {
  source?: string | null;
  description?: string | null;
}): boolean {
  if (task.source !== COUNCIL_TASK_SOURCE) return false;
  return typeof task.description === 'string' && TAG_PATTERN.test(task.description);
}

/** The council session that generated a board task, when identifiable. */
export function councilSessionIdFromTask(task: {
  source?: string | null;
  description?: string | null;
}): string | null {
  if (task.source !== COUNCIL_TASK_SOURCE) return null;
  if (typeof task.description !== 'string') return null;
  const match = TAG_PATTERN.exec(task.description);
  return match ? match[1] : null;
}

/** Section 19.6 operation identity for one planned action task. */
export function councilActionOperationId(input: {
  sessionId: string;
  verdictRevision: number;
  actionId: string;
  planHash: string;
}): string {
  return `council:${input.sessionId}:verdict:${input.verdictRevision}:action:${input.actionId}:plan:${input.planHash}`;
}

/** Operation identity for the single canonical parent task. */
export function councilParentOperationId(sessionId: string): string {
  return `council:${sessionId}:parent`;
}

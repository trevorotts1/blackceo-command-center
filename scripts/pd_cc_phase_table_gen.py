#!/usr/bin/env python3
"""pd_cc_phase_table_gen.py — generate the Command Center's presentation phase
table FROM the pipeline manifest, so the two can never drift again.

Before this generator src/lib/presentation-phases.ts was a hand-typed table
pinned to manifest version 70: 17 phases of manifest version 75 were unknown to
it and 9 phases it waited on no longer existed. The table now comes from the
vendored manifest plus a label file that only names the client-facing steps.

Inputs
  --manifest  PIPELINE-MANIFEST.json  (a byte copy: config/PIPELINE-MANIFEST.vendored.json)
  --labels    cc-phase-labels.json    (config/cc-phase-labels.json; shape below)
Output
  --out       src/lib/presentation-phases.generated.ts

cc-phase-labels.json shape
  {"steps": ["Getting Started","Research","Script","Design","Your Style Pick","Images",
             "Sales Page","Checkout","Video Sales Page","Speaker Kit","Audio and Video",
             "Quality Check","Delivery"],
   "phase_to_step": {"P-0.5-RESEARCH": "Research", ...one row for EVERY manifest phase id...},
   "owner_action_phases": ["P-STYLE-PICK"],
   "branch_steps": {"Sales Page": "want_sales_checkout", "Checkout": "want_sales_checkout",
                    "Video Sales Page": "want_vsl_page"}}

The thirteen steps are the client-facing lifecycle. A branch step exists only
for a run that elected the branch named by branch_steps.

Refuses (exit 1) when
  - a manifest phase id has no row in phase_to_step        (nothing may be invisible)
  - phase_to_step names an id the manifest does not have   (nothing may be waited on forever — this is also what
                                                            makes a retired phase id unrepresentable)
  - a row points at a step that is not in steps[]
  - a branch step is not in steps[]
  - an executor kind "human" phase is not listed in owner_action_phases
  - owner_action_phases names an id the manifest does not have

Exit codes: 0 written, 1 refused, 2 cannot run. --check compares without writing
(exit 1 when the file on disk differs from what would be generated).
STDLIB ONLY.
"""
import argparse
import json
import sys


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", required=True)
    ap.add_argument("--labels", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    try:
        with open(args.manifest, encoding="utf-8") as fh:
            manifest = json.load(fh)
        with open(args.labels, encoding="utf-8") as fh:
            labels = json.load(fh)
        phases = sorted(manifest["phases"], key=lambda p: p.get("order", 0))
        steps, table = labels["steps"], labels["phase_to_step"]
    except (OSError, ValueError, KeyError, TypeError) as exc:
        print("CANNOT RUN: %s" % exc)
        return 2

    ids = [p["id"] for p in phases]
    known = set(ids)
    owners = labels.get("owner_action_phases", [])
    branch_steps = labels.get("branch_steps", {})
    problems = []
    problems += ["manifest phase %s has no step (it would be invisible on the board)" % i
                 for i in ids if i not in table]
    problems += ["label table names %s, which the manifest does not have (a step would wait forever)" % i
                 for i in sorted(table) if i not in known]
    problems += ["%s points at unknown step %r" % (i, s) for i, s in sorted(table.items()) if s not in steps]
    problems += ["branch step %r is not in steps[]" % s for s in sorted(branch_steps) if s not in steps]
    problems += ["owner_action_phases names %s, which the manifest does not have" % i
                 for i in owners if i not in known]
    humans = [p["id"] for p in phases
              if isinstance(p.get("executor"), dict) and p["executor"].get("kind") == "human"]
    problems += ["human phase %s is not listed in owner_action_phases" % i
                 for i in humans if i not in owners]
    if problems:
        print("REFUSED: %d problem(s)" % len(problems))
        for line in problems:
            print("  - %s" % line)
        return 1

    lines = [
        "// GENERATED by pd_cc_phase_table_gen.py from PIPELINE-MANIFEST.vendored.json - DO NOT EDIT BY HAND.",
        "// Run `npm run check:phases` to prove this file is current.",
        "// manifest_version %s, %d phases, %d steps." % (manifest.get("manifest_version"), len(ids), len(steps)),
        "",
        "export const MANIFEST_VERSION = %s;" % json.dumps(manifest.get("manifest_version")),
        "export const STEPS = %s as const;" % json.dumps(steps),
        "export const OWNER_ACTION_PHASES: readonly string[] = %s;" % json.dumps(owners),
        "export const BRANCH_STEPS: Record<string, string> = %s;" % json.dumps(branch_steps, sort_keys=True),
        "",
        "export interface ManifestPhase {",
        "  id: string;",
        "  order: number;",
        "  step: string;",
        "  defersUnless: string | null;",
        "}",
        "",
        "export const PHASES: ReadonlyArray<ManifestPhase> = [",
    ]
    for p in phases:
        lines.append("  { id: %s, order: %s, step: %s, defersUnless: %s }," % (
            json.dumps(p["id"]), json.dumps(p.get("order", 0)), json.dumps(table[p["id"]]),
            json.dumps(p.get("defers_unless"))))
    lines.append("];")
    text = "\n".join(lines) + "\n"
    if args.check:
        try:
            with open(args.out, encoding="utf-8") as fh:
                same = fh.read() == text
        except OSError:
            same = False
        print("phase table is %s" % ("current" if same else "STALE - regenerate"))
        return 0 if same else 1
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote %s (%d phases, %d steps)" % (args.out, len(ids), len(steps)))
    return 0


if __name__ == "__main__":
    sys.exit(main())

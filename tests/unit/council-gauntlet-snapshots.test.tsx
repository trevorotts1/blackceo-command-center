function councilCss(): string {
  return CSS_FILES.map((f) =>
    fs.readFileSync(path.join(REPO_ROOT, f), 'utf8'),
  ).join('\n');
}

function snapshotHtml(title: string, bodyHtml: string, extraCss = ''): string {
  return [
    '<!doctype html>',
    '<!-- CWE-044 gauntlet snapshot. Synthetic fixtures only (CWE-032/CWE-034',
    '     component fixtures and the CWE-003 canonical brief fixture); no real',
    '     client, session, or model output. Generated by rendering the real',
    '     components of this tree in the repo component harness (vitest +',
    '     jsdom) with the tree\'s real council CSS inlined. Regenerate with:',
    '     npx vitest run --config vitest.council-gauntlet.config.ts -->',
    `<html><head><meta charset="utf-8"><title>${title}</title>`,
    `<style>\n${councilCss()}\n${extraCss}\n</style></head>`,
    `<body style="margin:0">${bodyHtml}</body></html>`,
    '',
  ].join('\n');
}

function writeSnapshot(name: string, html: string) {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  fs.writeFileSync(path.join(OUT_DIR, name), html);
}


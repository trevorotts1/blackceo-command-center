/* ── Transport stub: same shape as CWE-034's render suite ─────────── */
function snapshotOf(events: CouncilWireEvent[]): CouncilResyncSnapshot {
  const journal = events.map((e) => ({
    event_id: e.event_id,
    type: e.type,
    sequence: e.sequence,
    from_state: e.from_state,
    to_state: e.to_state,
    actor_subject: e.actor_subject,
    payload: e.payload,
    created_at: e.occurred_at,
  }));
  const projection = projectSession(FIXTURE_SCOPE, journal);
  if (!projection) throw new Error('fixture projection failed');
  return {
    kind: 'snapshot',
    session_id: FIXTURE_SESSION_ID,
    projection,
    last_sequence: events.reduce((max, e) => Math.max(max, e.sequence), 0),
  };
}

class StaticTransport implements CouncilSessionTransport {
  constructor(private readonly snap: CouncilCatchUp) {}
  snapshot(): Promise<CouncilCatchUp> {
    return Promise.resolve(this.snap);
  }
  page(): Promise<CouncilCatchUp> {
    return Promise.resolve({
      kind: 'page',
      page: {
        kind: 'events',
        session_id: FIXTURE_SESSION_ID,
        events: [],
        last_sequence: 0,
        has_more: false,
      },
    });
  }
  openStream(
    _sessionId: string,
    _after: number,
    _handlers: CouncilStreamHandlers,
  ): { close: () => void } {
    return { close: () => undefined };
  }
}

